import { Link } from "react-router-dom";
import { ExternalLink } from "lucide-react";

import Logo from "../shell/Logo.jsx";
import { FOOTER_LINKS } from "../../constants/marketing.js";

/**
 * Site footer.
 *
 * Internal destinations use react-router `Link` so they do not trigger a full
 * reload; anchors and external URLs stay plain `<a>`. External links get a
 * visible icon plus rel="noreferrer noopener".
 */
export default function SiteFooter() {
  return (
    <footer className="site-footer">
      <div className="container">
        <div className="site-footer__grid">
          <div>
            <Logo />
            <p className="site-footer__blurb">
              A multi-agent research workspace. Plan, retrieve, analyse, write, and cite — over the
              web, your documents, or both.
            </p>
          </div>

          {FOOTER_LINKS.map((group) => (
            <nav key={group.id} aria-label={group.title}>
              <p className="site-footer__title">{group.title}</p>
              <div className="site-footer__links">
                {group.links.map((link) =>
                  link.external ? (
                    <a
                      key={link.label}
                      href={link.href}
                      target="_blank"
                      rel="noreferrer noopener"
                      className="row"
                      style={{ gap: "var(--space-2)" }}
                    >
                      {link.label}
                      <ExternalLink size={12} aria-hidden="true" />
                    </a>
                  ) : link.href.startsWith("/#") || link.href.startsWith("#") ? (
                    <a key={link.label} href={link.href}>
                      {link.label}
                    </a>
                  ) : (
                    <Link key={link.label} to={link.href}>
                      {link.label}
                    </Link>
                  ),
                )}
              </div>
            </nav>
          ))}
        </div>

        <div className="site-footer__bottom">
          <p>© {new Date().getFullYear()} ResearchOS. Built as an open research workspace.</p>
          <p>Reports are generated by language models — verify anything that matters.</p>
        </div>
      </div>
    </footer>
  );
}
